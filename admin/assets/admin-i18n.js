window.ADMIN_LANG_KEY = "admin_ui_lang";
window.getAdminLang = function () {
  try {
    var saved = localStorage.getItem(window.ADMIN_LANG_KEY);
    if (saved && window.ADMIN_I18N["common.save"][saved]) return saved;
  } catch (e) {}
  return "kz";
};
window.setAdminLang = function (lang) {
  try { localStorage.setItem(window.ADMIN_LANG_KEY, lang); } catch (e) {}
};
window.adminT = function (key) {
  var entry = window.ADMIN_I18N[key];
  if (!entry) return key;
  var lang = window.getAdminLang();
  return entry[lang] !== undefined ? entry[lang] : entry.kz;
};
